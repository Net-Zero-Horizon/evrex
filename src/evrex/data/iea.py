def get_iea_ev_stock(country_iso: str) -> EVValidationData:
    """Get bundled IEA EV stock data for a country.

    Parameters
    ----------
    country_iso : str
        ISO-3 country code (e.g. ``"USA"``, ``"CHN"``).

    Returns
    -------
    EVValidationData
        Validation data with years and stock counts (units, not thousands).
    """
    iso = country_iso.upper()
    stock_data = IEA_EV_STOCK.get(iso)

    if stock_data is None:
        return EVValidationData(
            label=f"IEA EV Stock ({iso})",
            years=[],
            ev_stock=[],
            source="iea",
        )

    years = sorted(stock_data.keys())
    stock = [stock_data[y] * 1000 for y in years]  # thousands -> units

    return EVValidationData(
        label=f"IEA EV Stock ({iso})",
        years=years,
        ev_stock=stock,
        source="iea",
    )
